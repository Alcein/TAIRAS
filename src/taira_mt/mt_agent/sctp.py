"""Compile retrieved Thought Patterns into a legal public action frontier.

SCTP does not itself decide which proposal wins.  It retrieves the multi-scale
TAIRA Skills, applies their SOP/query-policy contracts to the observed public
state, and exposes competing legal operations to CIV.  This separation keeps
``state perception -> Skill experience -> value selection`` explicit.
"""

from __future__ import annotations

from pydantic import Field

from taira_mt.benchmark.schemas import BenchmarkActionType, BenchmarkSystemAction
from taira_mt.models import StrictModel
from taira_mt.mt_agent.memory import PublicDialogueMemory
from taira_mt.mt_agent.retrieval import CatalogRetrievalResult, LexicalCatalogRetriever, SearchSpec
from taira_mt.mt_agent.skills import (
    QueryPolicy,
    SkillMatch,
    SkillRetrieval,
    ThoughtPatternLibrary,
)
from taira_mt.mt_agent.state import (
    DecisionSufficientUserState,
    DialoguePhase,
    DisclosureStatus,
    DSUSDecisionPosterior,
    RecommendationReadiness,
)

SCTP_COMPILER_VERSION = "sctp_skill_frontier_compiler_v2"


class SkillActionProposal(StrictModel):
    """One public action generated by a semantic + interaction Skill pair."""

    proposal_id: str = Field(min_length=1)
    state_hypothesis_id: str = Field(min_length=1)
    state_hypothesis_probability: float = Field(gt=0.0, le=1.0)
    state_hypothesis: DecisionSufficientUserState
    semantic_skill_id: str
    interaction_skill_id: str
    semantic_match_score: float
    interaction_match_score: float
    action: BenchmarkSystemAction
    search_spec: SearchSpec | None = None
    retrieval: CatalogRetrievalResult | None = None
    sop_operation: str = Field(min_length=1)
    insight_summary: str = Field(min_length=1)


class SCTPActionFrontier(StrictModel):
    """All legal state-conditioned operations before CIV makes a choice."""

    compiler_id: str
    state: DecisionSufficientUserState
    skill_retrieval: SkillRetrieval
    state_hypotheses: list[SCTPStateHypothesis] = Field(min_length=1)
    proposals: list[SkillActionProposal] = Field(min_length=1)


class SCTPStateHypothesis(StrictModel):
    """A public DSUS state candidate used only for first-turn action value comparison."""

    hypothesis_id: str = Field(min_length=1)
    probability: float = Field(gt=0.0, le=1.0)
    state: DecisionSufficientUserState


def _unique(values: list[str]) -> list[str]:
    output: list[str] = []
    seen: set[str] = set()
    for value in values:
        cleaned = " ".join(value.split())
        if cleaned and cleaned.casefold() not in seen:
            seen.add(cleaned.casefold())
            output.append(cleaned)
    return output


class SCTPSkillCompiler:
    """Turn a retrieved Thought-Pattern library view into typed public actions."""

    compiler_id = SCTP_COMPILER_VERSION

    def __init__(
        self,
        *,
        library: ThoughtPatternLibrary,
        semantic_limit: int = 2,
        interaction_limit: int = 3,
        shortlist_k: int = 50,
        recommendation_k: int = 10,
        include_initial_counterfactuals: bool = False,
    ) -> None:
        if semantic_limit < 1 or interaction_limit < 1:
            raise ValueError("Skill retrieval limits must be positive")
        if not 1 <= recommendation_k <= shortlist_k <= 50:
            raise ValueError("require 1 <= recommendation_k <= shortlist_k <= 50")
        self.library = library
        self.semantic_limit = semantic_limit
        self.interaction_limit = interaction_limit
        self.shortlist_k = shortlist_k
        self.recommendation_k = recommendation_k
        self.include_initial_counterfactuals = include_initial_counterfactuals
        self.compiler_id = (
            f"{SCTP_COMPILER_VERSION}:{'multi_state' if include_initial_counterfactuals else 'single_state'}"
        )

    @staticmethod
    def _query_terms_for_policy(
        *,
        state: DecisionSufficientUserState,
        policy: QueryPolicy,
    ) -> tuple[list[str], list[str], list[str]]:
        frame = state.retrieval_frame
        must = list(frame.must_terms)
        preferred = list(frame.preferred_terms)
        avoid = list(frame.avoid_terms)
        if policy == QueryPolicy.AUDIENCE_FIT:
            must = _unique([*must, *preferred])
            preferred = []
        elif policy == QueryPolicy.MULTI_OCCASION:
            preferred = _unique([*preferred, *state.unresolved_axes])
        elif policy == QueryPolicy.FEEDBACK_REPAIR:
            must = _unique([*must, *preferred])
            preferred = []
        elif policy == QueryPolicy.TAXONOMY_CLARIFY:
            # The associated interaction Skill should normally ask; retaining
            # the original frame makes any competing recommendation auditable.
            preferred = _unique([*preferred, *state.unresolved_axes])
        return _unique(must), _unique(preferred), _unique(avoid)

    def _search_spec(
        self,
        *,
        memory: PublicDialogueMemory,
        state: DecisionSufficientUserState,
        policy: QueryPolicy,
    ) -> SearchSpec:
        must, preferred, avoid = self._query_terms_for_policy(state=state, policy=policy)
        target_type = state.retrieval_frame.target_type
        return SearchSpec(
            query=memory.retrieval_text,
            target_type="" if target_type == "product" else target_type,
            must_terms=must,
            preferred_terms=preferred,
            avoid_terms=avoid,
            excluded_item_ids=(
                memory.previously_recommended_item_ids
                if state.recommendation_readiness == RecommendationReadiness.REPAIR_RECOMMEND
                else []
            ),
            ranking_k=self.shortlist_k,
        )

    @staticmethod
    def _question_for_state(state: DecisionSufficientUserState) -> tuple[str, str]:
        axis = state.unresolved_axes[0] if state.unresolved_axes else "the deciding preference"
        if state.disclosure_status == DisclosureStatus.CONFLICT:
            return axis, f"To make the trade-off clear, which requirement should matter most: {axis}?"
        if state.disclosure_status == DisclosureStatus.AMBIGUOUS:
            return axis, f"Which interpretation should I use for {axis}?"
        return axis, f"What is most important to you about {axis}?"

    @staticmethod
    def _insight_summary(*, semantic_skill_id: str, interaction_skill_id: str, library: ThoughtPatternLibrary) -> str:
        semantic = library.skill(semantic_skill_id)
        interaction = library.skill(interaction_skill_id)
        return f"{semantic.insights[0].principle} {interaction.insights[0].principle}"

    def _recommendation_proposal(
        self,
        *,
        semantic_match: SkillMatch,
        interaction_match: SkillMatch,
        memory: PublicDialogueMemory,
        state: DecisionSufficientUserState,
        retriever: LexicalCatalogRetriever,
        state_hypothesis_id: str,
        state_hypothesis_probability: float,
    ) -> SkillActionProposal | None:
        semantic = self.library.skill(semantic_match.pattern_id)
        spec = self._search_spec(memory=memory, state=state, policy=semantic.query_policy)
        retrieval = retriever.search(spec)
        if not retrieval.results:
            return None
        item_ids = [item.item_id for item in retrieval.results[: self.recommendation_k]]
        first = retrieval.results[0]
        interaction = self.library.skill(interaction_match.pattern_id)
        return SkillActionProposal(
            proposal_id=f"{state_hypothesis_id}__{semantic.pattern_id}__{interaction.pattern_id}__recommend",
            state_hypothesis_id=state_hypothesis_id,
            state_hypothesis_probability=state_hypothesis_probability,
            state_hypothesis=state,
            semantic_skill_id=semantic.pattern_id,
            interaction_skill_id=interaction.pattern_id,
            semantic_match_score=semantic_match.score,
            interaction_match_score=interaction_match.score,
            action=BenchmarkSystemAction(
                action_type=BenchmarkActionType.RECOMMEND,
                item_ids=item_ids,
                utterance=(f"I found {len(item_ids)} catalog-grounded options. My leading option is {first.title}."),
            ),
            search_spec=spec,
            retrieval=retrieval,
            sop_operation="recommend",
            insight_summary=self._insight_summary(
                semantic_skill_id=semantic.pattern_id,
                interaction_skill_id=interaction.pattern_id,
                library=self.library,
            ),
        )

    def _ask_proposal(
        self,
        *,
        semantic_match: SkillMatch,
        interaction_match: SkillMatch,
        state: DecisionSufficientUserState,
        state_hypothesis_id: str,
        state_hypothesis_probability: float,
    ) -> SkillActionProposal:
        target, utterance = self._question_for_state(state)
        semantic = self.library.skill(semantic_match.pattern_id)
        interaction = self.library.skill(interaction_match.pattern_id)
        return SkillActionProposal(
            proposal_id=f"{state_hypothesis_id}__{semantic.pattern_id}__{interaction.pattern_id}__ask",
            state_hypothesis_id=state_hypothesis_id,
            state_hypothesis_probability=state_hypothesis_probability,
            state_hypothesis=state,
            semantic_skill_id=semantic.pattern_id,
            interaction_skill_id=interaction.pattern_id,
            semantic_match_score=semantic_match.score,
            interaction_match_score=interaction_match.score,
            action=BenchmarkSystemAction(
                action_type=BenchmarkActionType.ASK,
                question_target=target,
                utterance=utterance,
            ),
            sop_operation="ask",
            insight_summary=self._insight_summary(
                semantic_skill_id=semantic.pattern_id,
                interaction_skill_id=interaction.pattern_id,
                library=self.library,
            ),
        )

    def _stop_proposal(
        self,
        *,
        semantic_match: SkillMatch,
        interaction_match: SkillMatch,
        state: DecisionSufficientUserState,
        state_hypothesis_id: str,
        state_hypothesis_probability: float,
    ) -> SkillActionProposal:
        semantic = self.library.skill(semantic_match.pattern_id)
        interaction = self.library.skill(interaction_match.pattern_id)
        return SkillActionProposal(
            proposal_id=f"{state_hypothesis_id}__{semantic.pattern_id}__{interaction.pattern_id}__stop",
            state_hypothesis_id=state_hypothesis_id,
            state_hypothesis_probability=state_hypothesis_probability,
            state_hypothesis=state,
            semantic_skill_id=semantic.pattern_id,
            interaction_skill_id=interaction.pattern_id,
            semantic_match_score=semantic_match.score,
            interaction_match_score=interaction_match.score,
            action=BenchmarkSystemAction(
                action_type=BenchmarkActionType.STOP,
                utterance="I cannot make a catalog-grounded recommendation without a usable public decision path.",
            ),
            sop_operation="safe_stop",
            insight_summary=self._insight_summary(
                semantic_skill_id=semantic.pattern_id,
                interaction_skill_id=interaction.pattern_id,
                library=self.library,
            ),
        )

    def _initial_state_hypotheses(
        self,
        *,
        memory: PublicDialogueMemory,
        state: DecisionSufficientUserState,
        decision_posterior: DSUSDecisionPosterior | None,
    ) -> list[SCTPStateHypothesis]:
        """Expose one public counterfactual at an uncertain initial decision.

        The second hypothesis is not a hidden benchmark route.  It simply asks
        CIV to compare the observed DSUS interpretation against the opposite
        legal first-turn operation before a user has paid an interaction cost.
        Later turns have visible transition evidence, so they deliberately use
        only the primary state.
        """

        primary = SCTPStateHypothesis(hypothesis_id="primary", probability=1.0, state=state)
        if not self.include_initial_counterfactuals or memory.completed_action_count != 0:
            return [primary]
        if decision_posterior is None:
            primary_probability = min(0.80, max(0.56, 0.56 + 0.16 * state.confidence))
        else:
            ask_probability, recommend_probability, _ = decision_posterior.public_action_probabilities()
            if state.recommendation_readiness == RecommendationReadiness.ASK_DECISIVE:
                primary_probability = ask_probability
                alternative_probability = recommend_probability
            else:
                primary_probability = recommend_probability
                alternative_probability = ask_probability
            mass = primary_probability + alternative_probability
            if mass <= 0.0:
                primary_probability = 0.5
            else:
                primary_probability /= mass
            primary_probability = min(0.999, max(0.001, primary_probability))
        if state.recommendation_readiness == RecommendationReadiness.ASK_DECISIVE:
            alternative = state.model_copy(
                update={
                    "dialogue_phase": DialoguePhase.RECOMMENDATION,
                    "disclosure_status": DisclosureStatus.SUFFICIENT,
                    "unresolved_axes": [],
                    "recommendation_readiness": RecommendationReadiness.RECOMMEND_NOW,
                    "confidence": 1.0 - primary_probability,
                    "public_evidence_summary": (
                        "Counterfactual first-turn hypothesis: the visible request may already support a "
                        "catalog-grounded recommendation."
                    ),
                },
                deep=True,
            )
        else:
            target = state.retrieval_frame.target_type or "product"
            alternative = state.model_copy(
                update={
                    "dialogue_phase": DialoguePhase.ELICITATION,
                    "disclosure_status": DisclosureStatus.MISSING_DECISIVE,
                    "unresolved_axes": [f"the product property that should matter most for this {target}"],
                    "recommendation_readiness": RecommendationReadiness.ASK_DECISIVE,
                    "confidence": 1.0 - primary_probability,
                    "public_evidence_summary": (
                        "Counterfactual first-turn hypothesis: one public preference may still change "
                        "the ranking materially."
                    ),
                },
                deep=True,
            )
        return [
            primary.model_copy(update={"probability": primary_probability}),
            SCTPStateHypothesis(
                hypothesis_id="counterfactual",
                probability=1.0 - primary_probability,
                state=alternative,
            ),
        ]

    def _compile_for_hypothesis(
        self,
        *,
        memory: PublicDialogueMemory,
        hypothesis: SCTPStateHypothesis,
        retriever: LexicalCatalogRetriever,
    ) -> tuple[SkillRetrieval, list[SkillActionProposal]]:
        state = hypothesis.state
        skill_retrieval = self.library.retrieve(
            memory=memory,
            state=state,
            limit_per_layer=max(self.semantic_limit, self.interaction_limit),
        )
        semantic_matches = skill_retrieval.semantic_matches[: self.semantic_limit]
        interaction_matches = skill_retrieval.interaction_matches[: self.interaction_limit]
        proposals: list[SkillActionProposal] = []
        seen_action_keys: set[tuple[str, str, str]] = set()
        for interaction_match in interaction_matches:
            interaction = self.library.skill(interaction_match.pattern_id)
            for semantic_match in semantic_matches:
                for action_type in interaction.action_types:
                    key = (semantic_match.pattern_id, interaction_match.pattern_id, action_type.value)
                    if key in seen_action_keys:
                        continue
                    seen_action_keys.add(key)
                    proposal: SkillActionProposal | None
                    if action_type == BenchmarkActionType.RECOMMEND:
                        proposal = self._recommendation_proposal(
                            semantic_match=semantic_match,
                            interaction_match=interaction_match,
                            memory=memory,
                            state=state,
                            retriever=retriever,
                            state_hypothesis_id=hypothesis.hypothesis_id,
                            state_hypothesis_probability=hypothesis.probability,
                        )
                    elif action_type == BenchmarkActionType.ASK:
                        proposal = self._ask_proposal(
                            semantic_match=semantic_match,
                            interaction_match=interaction_match,
                            state=state,
                            state_hypothesis_id=hypothesis.hypothesis_id,
                            state_hypothesis_probability=hypothesis.probability,
                        )
                    elif action_type == BenchmarkActionType.STOP:
                        proposal = self._stop_proposal(
                            semantic_match=semantic_match,
                            interaction_match=interaction_match,
                            state=state,
                            state_hypothesis_id=hypothesis.hypothesis_id,
                            state_hypothesis_probability=hypothesis.probability,
                        )
                    else:
                        proposal = None
                    if proposal is not None:
                        proposals.append(proposal)
        return skill_retrieval, proposals

    def compile(
        self,
        *,
        memory: PublicDialogueMemory,
        state: DecisionSufficientUserState,
        retriever: LexicalCatalogRetriever,
        decision_posterior: DSUSDecisionPosterior | None = None,
    ) -> SCTPActionFrontier:
        hypotheses = self._initial_state_hypotheses(
            memory=memory,
            state=state,
            decision_posterior=decision_posterior,
        )
        primary_retrieval: SkillRetrieval | None = None
        proposals: list[SkillActionProposal] = []
        for hypothesis in hypotheses:
            skill_retrieval, hypothesis_proposals = self._compile_for_hypothesis(
                memory=memory,
                hypothesis=hypothesis,
                retriever=retriever,
            )
            if hypothesis.hypothesis_id == "primary":
                primary_retrieval = skill_retrieval
            proposals.extend(hypothesis_proposals)
        if not proposals:
            raise RuntimeError("SCTP retrieval produced no legal public action proposal")
        if primary_retrieval is None:  # pragma: no cover - primary is always constructed above
            raise RuntimeError("SCTP did not compile the primary DSUS hypothesis")
        return SCTPActionFrontier(
            compiler_id=self.compiler_id,
            state=state,
            skill_retrieval=primary_retrieval,
            state_hypotheses=hypotheses,
            proposals=proposals,
        )
